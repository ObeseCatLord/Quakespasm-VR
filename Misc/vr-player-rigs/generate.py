#!/usr/bin/env python3
"""Generate Quake/vr_player_rigs.h from calibrations.py and an installed game tree.

Reads the game tree only to compute each reference model's geometry signature
(the same value as VR_WeaponFamilySignature) and to check that the picked frame
exists. No model data is written to the header.
"""
import argparse
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..', 'vr-weapon-families'))
sys.path.insert(0, HERE)
import quakefs  # noqa: E402
from calibrations import PICKS  # noqa: E402


def c_float(value):
    text = '%g' % float(value)
    return text + ('f' if '.' in text or 'e' in text else '.0f')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--base', default=os.environ.get('QSVR_GAME_BASE'), required=False,
                        help='game base directory that holds id1 and the mods')
    parser.add_argument('--out', default=os.path.join(HERE, '..', '..', 'Quake', 'vr_player_rigs.h'))
    args = parser.parse_args()
    if not args.base:
        parser.error('--base or QSVR_GAME_BASE is required')
    rows, seen = [], {}
    for pick in PICKS:
        files = quakefs.game_files(os.path.join(args.base, pick.game))
        model = quakefs.parse_mdl(quakefs.read(files[pick.model]))
        if model is None:
            raise SystemExit('%s/%s is not a version 6 MDL' % (pick.game, pick.model))
        if not 0 <= pick.frame < len(model['frames']) or len(pick.joints) != 19:
            raise SystemExit('bad pick %s' % pick.key)
        signature = quakefs.signature(model)
        if signature in seen:
            raise SystemExit('%s duplicates %s' % (pick.key, seen[signature]))
        seen[signature] = pick.key
        rows.append((signature, pick))
    lines = [
        '/* Generated by Misc/vr-player-rigs/generate.py from calibrations.py. Do not edit. */',
        '#ifndef VR_PLAYER_RIGS_H',
        '#define VR_PLAYER_RIGS_H',
        '',
        '/* Joint positions in the reference frame\'s model space (x forward, y left,',
        ' * z up), in r_avatar semantic order MD5_VRIK_HIP..MD5_VRIK_FOOT_R. */',
        'typedef struct vr_player_rig_s',
        '{',
        '\tunsigned long long signature;',
        '\tconst char *key;',
        '\tconst char *name;',
        '\tint ref_frame;',
        '\tfloat joint[19][3];',
        '} vr_player_rig_t;',
        '',
        'static const vr_player_rig_t vr_player_rigs[] = {',
    ]
    for signature, pick in sorted(rows, key=lambda r: r[1].key):
        joints = ',\n\t\t'.join('{%s}' % ', '.join(c_float(c) for c in p) for p in pick.joints)
        lines.append('\t{0x%016xull, "%s", "%s", %d, {\n\t\t%s}},' % (
            signature, pick.key, pick.name, pick.frame, joints))
    lines += ['};', '', '#endif', '']
    with open(args.out, 'w', newline='\n') as f:
        f.write('\n'.join(lines))
    print('%d rigs -> %s' % (len(rows), os.path.normpath(args.out)))


if __name__ == '__main__':
    main()
